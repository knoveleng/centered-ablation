TEXMAP = {"\u201d": "\\textquotedblright{}", "\u201c": "\\textquotedblleft{}", "\u2019": "\\textquoteright{}",
          "\u2018": "\\textquoteleft{}", "\u2026": "\\ldots{}", '"': "\\textquotedbl{}", "!": "!", "?": "?",
          "\\": "\\textbackslash{}", "_": "\\_", "&": "\\&", "#": "\\#", "%": "\\%", "$": "\\$", "{": "\\{", "}": "\\}",
          "~": "\\textasciitilde{}", "^": "\\textasciicircum{}", ",": ",", ".": "."}


def tok2tex(t):
    """One vocabulary token as LaTeX: keep ASCII and typographic quotes, mark anything else (emoji, CJK)."""
    out, odd = "", False
    for ch in t:
        if ch in TEXMAP:
            out += TEXMAP[ch]
        elif ch == " ":
            out += "\\textvisiblespace{}"
        elif ch.isascii() and (ch.isalnum() or ch in "-'()*/:;<>=+[]|@"):
            out += ch
        else:
            odd = True
    if odd and not any(c.isalpha() for c in t if c.isascii()):
        return "[non-Latin]" if not out else f"\\texttt{{{out}}}\\,[+sym.]"
    return f"\\texttt{{{out or '[space]'}}}"


